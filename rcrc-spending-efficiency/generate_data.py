# ============================================================================
# Roll-ups & assertions
# ============================================================================
def build():
    # SKEP roll-ups
    pillars_out = []
    ev_dates = ["2026-07-20", "2026-07-06", "2026-06-22", "2026-06-08", "2026-05-25"]
    for p in PILLARS:
        crits = []
        for ci, c in enumerate(p["criteria"]):
            s, m, v = c["scores"]
            for ei, e in enumerate(c["evidence"]):
                e.setdefault("owner", p["owner"])
                e.setdefault("updated", ev_dates[(ci + ei) % len(ev_dates)] if e["status"] != "غير متوفر" else "")
                e.setdefault("version", "1.0" if e["status"] == "متوفر" else ("0.9" if e["status"] == "قيد الإعداد" else "—"))
            ev_total = len(c["evidence"])
            ev_ready = sum(1 for e in c["evidence"] if e["status"] == "متوفر")
            crits.append({
                "code": c["code"], "name": c["name"],
                "selfScore": s, "simScore": m, "prevScore": v, "target": 5,
                "evidence": c["evidence"], "actions": c["actions"],
                "evTotal": ev_total, "evReady": ev_ready,
            })
        def mean(key):
            return round(sum(c[key] for c in crits) / len(crits), 2)
        pillars_out.append({
            "id": p["id"], "name": p["name"], "short": p["short"], "icon": p["icon"],
            "owner": p["owner"], "desc": p["desc"], "criteria": crits,
            "selfScore": mean("selfScore"), "simScore": mean("simScore"),
            "prevScore": mean("prevScore"),
        })

    overall = {
        "self": round(sum(p["selfScore"] for p in pillars_out) / len(pillars_out), 1),
        "sim": round(sum(p["simScore"] for p in pillars_out) / len(pillars_out), 1),
        "prev": round(sum(p["prevScore"] for p in pillars_out) / len(pillars_out), 1),
    }
    assert overall["self"] == 3.8, overall
    assert overall["sim"] == 3.5, overall
    assert overall["prev"] == 3.0, overall

    ev_total = sum(c["evTotal"] for p in pillars_out for c in p["criteria"])
    ev_ready = sum(c["evReady"] for p in pillars_out for c in p["criteria"])

    # Impact roll-ups from initiatives (single source of truth)
    identified = round(sum(i["estImpact"] for i in INITIATIVES), 1)
    approved = round(sum(i["approvedImpact"] for i in INITIATIVES), 1)
    realized = round(sum(i["realizedImpact"] for i in INITIATIVES), 1)
    documented = round(sum(i["realizedImpact"] for i in INITIATIVES if i["status"] == "مقفلة"), 1)
    assert documented <= realized <= approved <= identified

    # 2026 monthly reconciliation: realized = 2025 carry + 2026 months
    real_2026 = round(sum(m["real"] for m in IMPACT_MONTHLY_2026), 1)
    carry_2025 = round(realized - real_2026, 1)
    assert carry_2025 >= 0, (realized, real_2026)

    by_cat, by_prog, by_type = {}, {}, {}
    for i in INITIATIVES:
        by_cat.setdefault(i["category"], {"identified": 0, "realized": 0})
        by_cat[i["category"]]["identified"] += i["estImpact"]
        by_cat[i["category"]]["realized"] += i["realizedImpact"]
        by_prog.setdefault(i["program"], {"identified": 0, "realized": 0})
        by_prog[i["program"]]["identified"] += i["estImpact"]
        by_prog[i["program"]]["realized"] += i["realizedImpact"]
        by_type.setdefault(i["impactType"], {"identified": 0, "realized": 0})
        by_type[i["impactType"]]["identified"] += i["estImpact"]
        by_type[i["impactType"]]["realized"] += i["realizedImpact"]
    assert round(sum(v["realized"] for v in by_cat.values()), 1) == realized
    assert round(sum(v["identified"] for v in by_prog.values()), 1) == identified

    # Initiative commitment KPI reproducibility
    n = len(INITIATIVES)
    flagged = sum(1 for i in INITIATIVES if i["flag"] in ("متأخرة", "متعثرة"))
    commitment = round((1 - flagged / n) * 100, 1)
    assert commitment == 89.3, commitment
    total_cr = sum(i["changeRequests"] for i in INITIATIVES)
    cr_avg = round(total_cr / n, 2)

    # NOTE: seed KPI K-18/K-19 latest value should match commitment
    for k in KPIS:
        if k["id"] in ("K-18", "K-19"):
            k["series"][-1]["v"] = commitment
        if k["id"] == "K-20":
            k["series"][-1]["v"] = cr_avg

    f1 = round(real_2026 / BUDGET_APPROVED * 100, 1)  # cumulative YTD share (impact tab)

    # Initiative charters + documentation for initiatives past approval
    CHARTER_STAGES = ("معتمدة", "تنفيذ", "قياس الأثر", "مقفلة")
    for i in INITIATIVES:
        advanced = i["status"] in CHARTER_STAGES
        if advanced:
            i["charter"] = {
                "objective": f"تحقيق أثر مالي معتمد بقيمة {i['approvedImpact'] or i['estImpact']} مليون ريال عبر {i['treatment']}.",
                "activities": [
                    "اعتماد خط الأساس ومعادلة قياس الأثر مع الشؤون المالية",
                    "تنفيذ آلية المعالجة وفق الجدول الزمني المعتمد",
                    "قياس الأثر دورياً ورفع تقارير التقدم الربع سنوية",
                ],
                "risks": "تغير نطاق العقود أو تأخر التوريد؛ تُدار عبر اللجنة الإشرافية.",
                "dataNeeded": i["baselineMethod"],
                "mechanism": f"قياس الفرق عن خط الأساس ({i['baselineMethod']}) بتحقق الشؤون المالية قبل الاعتماد.",
            }
        i["docs"] = [
            {"name": "بطاقة الفرصة", "status": "متوفر"},
            {"name": "ميثاق المبادرة", "status": "متوفر" if advanced else ("قيد الإعداد" if i["status"] == "دراسة" else "غير متوفر")},
            {"name": "اعتماد الشؤون المالية لخط الأساس", "status": "متوفر" if i["financeValidated"] else "غير متوفر"},
            {"name": "تقرير قياس الأثر", "status": "متوفر" if i["status"] in ("قياس الأثر", "مقفلة") else ("قيد الإعداد" if i["status"] == "تنفيذ" else "غير متوفر")},
        ]

    # Funding request compliance — intake quality across ALL registered requests;
    # the entry gate guarantees 100% completeness inside the review chain.
    def fr_complete(r):
        return all(r["fiveStudies"].values()) and r["cdStudy"] and r["scopeDoc"] and r["valueDoc"]
    in_chain = [r for r in FUNDING_REQUESTS if r["stage"] not in ("الإعداد", "معاد للاستكمال")]
    assert all(fr_complete(r) for r in in_chain), "gate violation: incomplete request inside review chain"
    fr_compliance = round(sum(1 for r in FUNDING_REQUESTS if fr_complete(r)) / len(FUNDING_REQUESTS) * 100)

    # Budget totals
    budget_total = sum(c["approved"] for c in BUDGET_CHAPTERS)
    assert budget_total == BUDGET_APPROVED, budget_total

    # Status counts
    status_order = ["فرصة", "دراسة", "معتمدة", "تنفيذ", "قياس الأثر", "مقفلة"]
    by_status = {s: sum(1 for i in INITIATIVES if i["status"] == s) for s in status_order}
    assert sum(by_status.values()) == n

    data = {
        "meta": {
            "entity": "الهيئة الملكية لمدينة الرياض",
            "platform": "منصة استدامة كفاءة الإنفاق",
            "subtitle": "المنصة المركزية لأتمتة ممارسات كفاءة الإنفاق وأعمال فريق كفاءة الإنفاق",
            "rfp": "مشروع تمكين استدامة كفاءة الإنفاق — كراسة رقم 20000424",
            "asOf": AS_OF,
            "demo": True,
            "demoNote": "بيانات تجريبية لأغراض العرض — تُستبدل بالبيانات الفعلية عند التشغيل",
            "budgetApproved": BUDGET_APPROVED,
            "impactTarget2026": IMPACT_TARGET_2026,
        },
        "maturity": MATURITY,
        "assessmentCycle": ASSESSMENT_CYCLE,
        "pillars": pillars_out,
        "overall": overall,
        "evidence": {"total": ev_total, "ready": ev_ready,
                     "coverage": round(ev_ready / ev_total * 100)},
        "programs": PROGRAMS,
        "initiatives": INITIATIVES,
        "initiativeStats": {
            "total": n, "byStatus": by_status, "flagged": flagged,
            "commitment": commitment, "changeRequests": total_cr, "crAvg": cr_avg,
        },
        "impact": {
            "identified": identified, "approved": approved,
            "realized": realized, "documented": documented,
            "realized2026": real_2026, "carry2025": carry_2025,
            "target2026": IMPACT_TARGET_2026,
            "monthly2026": IMPACT_MONTHLY_2026,
            "byCategory": by_cat, "byProgram": by_prog, "byType": by_type,
            "budgetShare": f1,
        },
        "fundingRequests": FUNDING_REQUESTS,
        "frStats": {"compliance": fr_compliance,
                     "total": len(FUNDING_REQUESTS),
                     "inChain": len(in_chain)},
        "studies": STUDIES,
        "methodologies": METHODOLOGIES,
        "benchmarkInitiatives": BENCHMARK_INITIATIVES,
        "aiBenchmarks": AI_BENCHMARKS,
        "policies": POLICIES,
        "services": SERVICES,
        "budgetChapters": BUDGET_CHAPTERS,
        "spendingReviews": SPENDING_REVIEWS,
        "kpis": KPIS,
        "governance": GOVERNANCE,
        "capability": CAPABILITY,
        "reports": REPORTS,
    }
    return data

if __name__ == "__main__":
    data = build()
    out = os.path.join(HERE, "data.json")
